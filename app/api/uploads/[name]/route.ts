import { NextResponse } from "next/server";
import { readFile } from "fs/promises";
import path from "path";
import { db } from "@/lib/db";
import { getCurrentUser } from "@/lib/auth";
import { UPLOAD_DIR, contentTypeFor } from "@/lib/uploads";

/**
 * Serves a reference photo only to people who may see the request it belongs to:
 * the owning customer, or any provider (providers browse open requests to bid).
 */
export async function GET(_req: Request, { params }: { params: Promise<{ name: string }> }) {
  const user = await getCurrentUser();
  if (!user) return new NextResponse("Unauthorized", { status: 401 });

  const { name } = await params;
  // Filenames are generated by us (hex + extension); reject anything else before touching the disk.
  if (!/^[a-f0-9]{32}\.(jpg|png|webp)$/.test(name)) return new NextResponse("Not found", { status: 404 });

  const request = await db.request.findFirst({ where: { photoPath: name }, select: { customerId: true } });
  if (!request) return new NextResponse("Not found", { status: 404 });
  if (user.role === "CUSTOMER" && request.customerId !== user.id) {
    return new NextResponse("Forbidden", { status: 403 });
  }

  try {
    const bytes = await readFile(path.join(UPLOAD_DIR, name));
    return new NextResponse(bytes, {
      headers: { "Content-Type": contentTypeFor(name), "Cache-Control": "private, max-age=3600" },
    });
  } catch {
    return new NextResponse("Not found", { status: 404 });
  }
}
